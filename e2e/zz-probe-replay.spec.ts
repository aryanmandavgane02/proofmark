import { expect, test } from "@playwright/test";
const SHOTS = "/private/tmp/claude-501/-Users-aryanmandavgane-Documents-vscode-java-cou-Lab-3/01c9810c-dc51-42e5-bb52-4439f82e9289/scratchpad/p4";
test("probe: rule-change replay", async ({ page }) => {
  test.setTimeout(240_000);
  await page.goto("/");
  await page.getByRole("button", { name: /Start the live demo/ }).click();
  await expect(page).toHaveURL(/\/app$/);
  await page.goto("/app/insights");
  await page.getByLabel("Acting as").selectOption({ label: "Meera · Brand manager" });
  await expect(page.getByText("Switching…")).toHaveCount(0);
  const card = page.locator("#rule-MSG-01").locator("xpath=ancestor::div[contains(@class,'rounded')][1]");
  const t0 = Date.now();
  await page.getByRole("button", { name: "Propose clearer wording" }).first().click();
  await expect(page.getByText("Proposed clearer wording")).toBeVisible({ timeout: 90_000 });
  console.log("proposal after", Date.now() - t0, "ms:", await page.getByLabel("New wording for MSG-01").inputValue());
  const t1 = Date.now();
  await page.getByRole("button", { name: "Preview the effect on past decisions" }).click();
  await expect(page.getByText("Effect on past decisions, if published")).toBeVisible({ timeout: 90_000 });
  console.log("replay after", Date.now() - t1, "ms");
  console.log("summary:", await page.locator("#replay-MSG-01 p").first().innerText());
  for (const row of await page.locator("#replay-MSG-01 tbody tr").all()) console.log("  ", (await row.innerText()).replace(/\s+/g, " ").slice(0, 200));
  await page.screenshot({ path: `${SHOTS}/1-replay.png`, fullPage: true });
  await page.getByRole("button", { name: /Accept and publish as v2/ }).click();
  await expect(page.getByText(/Published rulebook v2/)).toBeVisible({ timeout: 60_000 });
  console.log("published:", await page.getByText(/Published rulebook v2/).innerText());
  await page.goto("/app/rulebook");
  const v2 = page.getByText("Replay of MSG-01 kept with v2");
  await expect(v2).toBeVisible();
  console.log("rulebook v2 summary:", await page.locator("div").filter({ has: v2 }).last().innerText().then((t) => t.replace(/\s+/g, " ").slice(0, 300)));
});
